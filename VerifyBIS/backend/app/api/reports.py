@router.get("")
def get_reports(
    db: Session = Depends(get_db),
):
    reports = (
        db.query(Report)
        .order_by(Report.created_at.desc())
        .all()
    )

    return {
        "count": len(reports),
        "reports": [
            serialize_report(report)
            for report in reports
        ],
    }


@router.post("/generate")
def generate_report(
    type: str = Query(
        "compliance",
        min_length=1,
    ),
    tender_id: int | None = Query(
        None,
        ge=1,
    ),
    db: Session = Depends(get_db),
):
    if type not in {"compliance", "tender_summary"}:
        raise HTTPException(
            status_code=400,
            detail=(
                "Unsupported report type. "
                "Use compliance or tender_summary."
            ),
        )

    query = db.query(TenderAnalysis)

    if tender_id is not None:
        tender = (
            query
            .filter(TenderAnalysis.id == tender_id)
            .first()
        )
    else:
        tender = (
            query
            .order_by(TenderAnalysis.created_at.desc())
            .first()
        )

    if not tender:
        raise HTTPException(
            status_code=404,
            detail="No tender analysis found.",
        )

    if type == "compliance":
        title = (
            f"Compliance Report - "
            f"{tender.filename or f'Tender {tender.id}'}"
        )
    else:
        title = (
            f"Tender Summary - "
            f"{tender.filename or f'Tender {tender.id}'}"
        )

    content = build_report_content(tender)

    report = Report(
        tender_id=tender.id,
        report_type=type,
        title=title,
        content=content,
    )

    db.add(report)
    db.commit()
    db.refresh(report)

    return serialize_report(report)


@router.get("/{report_id}")
def get_report(
    report_id: int,
    db: Session = Depends(get_db),
):
    report = (
        db.query(Report)
        .filter(Report.id == report_id)
        .first()
    )

    if not report:
        raise HTTPException(
            status_code=404,
            detail="Report not found.",
        )

    return serialize_report(report)


@router.get("/{report_id}/download")
def download_report(
    report_id: int,
    db: Session = Depends(get_db),
):
    report = (
        db.query(Report)
        .filter(Report.id == report_id)
        .first()
    )

    if not report:
        raise HTTPException(
            status_code=404,
            detail="Report not found.",
        )

    tender = None

    if report.tender_id:
        tender = (
            db.query(TenderAnalysis)
            .filter(TenderAnalysis.id == report.tender_id)
            .first()
        )

    if tender:
        pdf = build_tender_pdf(tender)
    else:
        pdf = build_text_pdf(report.title, report.content)

    filename = (
        f"BISQ-report-{report.id}.pdf"
    )

    return Response(
        content=pdf,
        media_type="application/pdf",
        headers={
            "Content-Disposition": (
                f'attachment; filename="{filename}"'
            )
        },
    )