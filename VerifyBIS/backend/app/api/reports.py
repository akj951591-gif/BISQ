    summary = escape(tender.summary or "No summary available.")

    finding_html = ""

    if not findings:
        finding_html = "<p>No findings were generated.</p>"
    else:
        for index, finding in enumerate(findings, start=1):
            requirement = escape(
                str(finding.get("requirement", ""))
            )
